#!/usr/bin/env python3
"""Wave 2 (E4B) tables: score with Wilson 95% interval, generated tokens, time, drafter acceptance per cell,
and exact McNemar tests on the same problems for thinking, drafter and weights. Writes RESULTS.md and
results.json. Reads only the .jsonl and .log files in this directory."""
import ast, json, math, os, statistics as st
from math import comb
HERE = os.path.dirname(os.path.abspath(__file__))
ARMS = ["repack-none", "repack-q4x", "google-none", "google-q4x"]
TASKS = ["gsm8k", "aime2025"]
def load(task, arm, th):
    base = os.path.join(HERE, f"{task}-{arm}-think{th}")
    rows = [json.loads(l) for l in open(base + ".jsonl")]
    summ = json.loads(open(base + ".log").read().strip().splitlines()[-1])
    return rows, summ
def wilson(k, n, z=1.959963984540054):
    p = k / n; d = 1 + z*z/n; c = (p + z*z/(2*n)) / d; h = z*math.sqrt(p*(1-p)/n + z*z/(4*n*n)) / d
    return c - h, c + h
def mcnemar(b, c):  # exact two-sided on discordant pairs
    n = b + c
    if n == 0: return 1.0
    k = min(b, c); return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2**n)
def timings(r):
    t = r.get("timings")
    if isinstance(t, str): t = ast.literal_eval(t)
    return t or {}
cells, R = {}, {}
for t in TASKS:
    for a in ARMS:
        for th in ("off", "on"):
            rows, s = load(t, a, th)
            R[(t, a, th)] = {r["id"]: bool(r.get("right")) for r in rows}
            k, n = sum(R[(t, a, th)].values()), len(rows)
            toks = [r.get("completion_tokens") or 0 for r in rows]
            dn = sum(timings(r).get("draft_n", 0) for r in rows); da = sum(timings(r).get("draft_n_accepted", 0) for r in rows)
            pn = sum(timings(r).get("predicted_n", 0) for r in rows); pm = sum(timings(r).get("predicted_ms", 0) for r in rows)
            lo, hi = wilson(k, n)
            cells[f"{t} {a} {th}"] = dict(task=t, arm=a, thinking=th, right=k, n=n, acc=k/n, lo=lo, hi=hi,
                truncated=s.get("truncated"), errors=s.get("errors"), wall_h=s["wall_s"]/3600,
                tokens_total=sum(toks), tokens_mean=st.mean(toks), tokens_median=st.median(toks),
                gen_tok_s=(pn / (pm/1000)) if pm else None, accept=(da/dn) if dn else None)
def pair(x, y, label):
    A, B = R[x], R[y]; ids = sorted(A)
    assert sorted(B) == ids
    b = sum(A[i] and not B[i] for i in ids); c = sum(B[i] and not A[i] for i in ids)
    return dict(test=label, a=" ".join(x), b=" ".join(y), only_a=b, only_b=c, net=c-b, p=mcnemar(b, c))
tests = []
for t in TASKS:
    for a in ARMS: tests.append(pair((t, a, "off"), (t, a, "on"), f"thinking {t} {a}: off -> on"))
    for w in ("repack", "google"):
        for th in ("off", "on"): tests.append(pair((t, f"{w}-none", th), (t, f"{w}-q4x", th), f"drafter {t} {w} thinking {th}: none -> q4x"))
    for d in ("none", "q4x"):
        for th in ("off", "on"): tests.append(pair((t, f"repack-{d}", th), (t, f"google-{d}", th), f"weights {t} drafter {d} thinking {th}: repack -> google"))
json.dump(dict(cells=cells, tests=tests), open(os.path.join(HERE, "results.json"), "w"), indent=1)
L = ["# E4B thinking study, wave 2 — results", "", "Generated by `analyze.py` from the `.jsonl` and `.log` files here. Tokens are all generated tokens per reply (thinking plus answer).", ""]
for t in TASKS:
    L += [f"## {t}", "", "| arm | thinking | right | score | 95% interval | cut off | mean tokens | hours | gen tok/s | drafter acceptance |", "|---|---|---|---|---|---|---|---|---|---|"]
    for a in ARMS:
        for th in ("off", "on"):
            c = cells[f"{t} {a} {th}"]
            L.append(f"| {a} | {th} | {c['right']}/{c['n']} | {c['acc']:.4f} | {c['lo']:.4f}–{c['hi']:.4f} | {c['truncated']} | {c['tokens_mean']:.0f} | {c['wall_h']:.2f} | {c['gen_tok_s']:.1f} | {'' if c['accept'] is None else f'{c[chr(97)+chr(99)+chr(99)+chr(101)+chr(112)+chr(116)]:.3f}'} |")
    L.append("")
L += ["## Paired tests (exact McNemar, same problems)", "", "| comparison | right only before | right only after | net | p |", "|---|---|---|---|---|"]
for x in tests: L.append(f"| {x['test']} | {x['only_a']} | {x['only_b']} | {x['net']:+d} | {x['p']:.4f} |")
open(os.path.join(HERE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
