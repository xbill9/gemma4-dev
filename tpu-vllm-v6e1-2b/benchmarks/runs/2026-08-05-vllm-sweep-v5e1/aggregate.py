#!/usr/bin/env python3
"""Aggregate sweep_results_v5e1.csv into results/summary.json and tables.md.

Cell keys and latency shapes follow serving-report.schema.json v1.1, so a cell here drops
into a report's throughput.sweep[] without renaming: nested {mean,median,p90,p99} under
ttft_ms / tpot_ms / itl_ms, and (input_len, concurrency) as the cell coordinates.

The source CSV records mean TPOT and mean ITL only — no median, no percentiles — so those
keys are absent rather than filled with the mean. per_stream_tok_per_s is derived from mean
TPOT for that reason, and is marked as such in tables.md.

Stdlib only (csv/json); pandas is not assumed anywhere in this repo.
"""

import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "sweep_results_v5e1.csv")
RESULTS = os.path.join(HERE, "results")


def num(row, key):
    v = row.get(key, "")
    if v in ("", None):
        return None
    try:
        f = float(v)
    except ValueError:
        return None
    return int(f) if f.is_integer() and key in ("concurrency", "input_len", "num_prompts") else f


def build():
    with open(CSV_PATH) as fh:
        rows = list(csv.DictReader(fh))

    cells = {}
    for r in rows:
        ctx = int(float(r["input_len"]))
        conc = int(float(r["concurrency"]))
        failed = num(r, "failed_requests") or 0
        cell = {
            "input_len": ctx,
            "concurrency": conc,
            "status": "ok" if failed == 0 else "failed",
            "request_rate_rps": num(r, "req_per_s"),
            "output_tok_per_s": num(r, "output_tok_per_s"),
            "total_tok_per_s": num(r, "total_tok_per_s"),
            "ttft_ms": {
                k: v
                for k, v in (
                    ("mean", num(r, "mean_ttft_ms")),
                    ("median", num(r, "median_ttft_ms")),
                    ("p99", num(r, "p99_ttft_ms")),
                )
                if v is not None
            },
            "tpot_ms": {k: v for k, v in (("mean", num(r, "mean_tpot_ms")),) if v is not None},
            "itl_ms": {k: v for k, v in (("mean", num(r, "mean_itl_ms")),) if v is not None},
            "completed": num(r, "successful_requests"),
        }
        mean_tpot = cell["tpot_ms"].get("mean")
        if mean_tpot:
            cell["per_stream_tok_per_s"] = round(1000.0 / mean_tpot, 2)
        cells[f"c{ctx}-u{conc}"] = cell

    summary = {
        "google/gemma-4-E2B-it": {
            "boot": {
                "model": "google/gemma-4-E2B-it",
                "max_model_len": None,
                "time_to_healthy_s": None,
                "_note": "not recorded by the CSV; see REPORT.md",
            },
            "cells": cells,
        }
    }
    os.makedirs(RESULTS, exist_ok=True)
    out = os.path.join(RESULTS, "summary.json")
    with open(out, "w") as fh:
        json.dump(summary, fh, indent=1, sort_keys=True)
        fh.write("\n")
    print(f"wrote {os.path.relpath(out, HERE)} ({len(cells)} cells)")
    return cells


def tables(cells):
    ctxs = sorted({c["input_len"] for c in cells.values()})
    concs = sorted({c["concurrency"] for c in cells.values()})

    def grid(title, pick, nd=0):
        lines = [f"### {title}", "", "| ctx \\ users | " + " | ".join(str(u) for u in concs) + " |"]
        lines.append("|---" * (len(concs) + 1) + "|")
        for ctx in ctxs:
            row = [f"| {ctx} "]
            for u in concs:
                c = cells.get(f"c{ctx}-u{u}")
                v = pick(c) if c else None
                row.append(f"|{v:,.{nd}f} " if isinstance(v, (int, float)) else "|— ")
            lines.append("".join(row) + "|")
        lines.append("")
        return lines

    out = [
        "# v5e-1 sweep tables — gemma-4-E2B-it",
        "",
        "Generated by `aggregate.py` from `sweep_results_v5e1.csv`. Do not hand-edit.",
        "",
    ]
    out += grid("Aggregate output tok/s", lambda c: c.get("output_tok_per_s"))
    out += grid("Total (prefill+decode) tok/s", lambda c: c.get("total_tok_per_s"))
    out += grid("Median TTFT ms", lambda c: c.get("ttft_ms", {}).get("median"), nd=1)
    out += grid("p99 TTFT ms", lambda c: c.get("ttft_ms", {}).get("p99"), nd=1)
    out += grid("Mean TPOT ms", lambda c: c.get("tpot_ms", {}).get("mean"), nd=2)
    out += grid("Per-stream tok/s (derived: 1000 / mean TPOT)", lambda c: c.get("per_stream_tok_per_s"), nd=1)
    path = os.path.join(HERE, "tables.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {os.path.relpath(path, HERE)}")


if __name__ == "__main__":
    tables(build())
